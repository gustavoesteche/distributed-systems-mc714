#!/usr/bin/env python3
"""Generate a Docker Compose file for an N-node experiment cluster.

The committed compose.yaml stays a friendly 4-node demo. Experiments need a
different node count, interval and topology, so run.py writes a throwaway
compose file into the run directory and passes it to `docker compose -f`.
"""

from __future__ import annotations

from pathlib import Path

IMAGE = "mc714-node:latest"
TOXIPROXY_IMAGE = "ghcr.io/shopify/toxiproxy:2.9.0"


def render(
    nodes: int,
    *,
    interval: str = "1s",
    extra_edges: int = 1,
    topology_seed: int = 42,
    max_neighbors: int | None = None,
    image: str = IMAGE,
    toxiproxy: bool = False,
    base_port: int = 8000,
) -> str:
    if nodes < 3:
        raise ValueError("nodes must be at least 3")
    if nodes > 9:
        raise ValueError("the toxiproxy {index} template supports at most 9 nodes")
    if max_neighbors is None:
        max_neighbors = min(3, nodes - 1)
    if not 2 <= max_neighbors <= nodes - 1:
        raise ValueError("max_neighbors must be between 2 and nodes-1")
    if extra_edges < 0:
        raise ValueError("extra_edges must be >= 0")

    peer_template = "http://toxiproxy:1000{index}" if toxiproxy else "http://{id}:8080"
    lines: list[str] = [
        "# Generated by experiments/compose_gen.py; do not edit by hand.",
        "services:",
    ]
    for k in range(1, nodes + 1):
        lines += [
            f"  node-{k}:",
            f"    image: {image}",
            f"    hostname: node-{k}",
            '    restart: "no"',
            "    environment:",
            f'      NODE_ID: "node-{k}"',
            f'      NODE_COUNT: "{nodes}"',
            f'      MAX_NEIGHBORS: "{max_neighbors}"',
            f'      EXTRA_EDGES: "{extra_edges}"',
            f'      TOPOLOGY_SEED: "{topology_seed}"',
            f'      GOSSIP_INTERVAL: "{interval}"',
            '      FAILURE_THRESHOLD: "3"',
            '      HTTP_TIMEOUT: "2s"',
            '      LOG_LEVEL: "info"',
            f'      PEER_URL_TEMPLATE: "{peer_template}"',
            "    ports:",
            f'      - "127.0.0.1:{base_port + k}:8080"',
            "    networks:",
            "      - gossip-net",
        ]

    if toxiproxy:
        lines += [
            "  toxiproxy:",
            f"    image: {TOXIPROXY_IMAGE}",
            '    restart: "no"',
            "    ports:",
            '      - "127.0.0.1:8474:8474"',
            "    networks:",
            "      - gossip-net",
        ]

    lines += [
        "networks:",
        "  gossip-net:",
        "    driver: bridge",
        "",
    ]
    return "\n".join(lines)


def write(path: Path, **kwargs) -> Path:
    path.write_text(render(**kwargs), encoding="utf-8")
    return path
